// A source-bound text archive, never imported project code. The browser can
// export a complete native-module game without network requests or a bundler.
import {readFile,writeFile,lstat} from 'node:fs/promises';
import {resolve,join} from 'node:path';
import {pathToFileURL} from 'node:url';
import {createHash} from 'node:crypto';
import {jsDependencies,assetDependencies,resolveLocal} from './browser-dependencies.mjs';
import {fileModuleArchive,fileModuleSource} from '../demos/horizon-lab/race-file-source.js';
const ROOT=resolve(import.meta.dirname,'..');
export const RUNTIME_ARCHIVE='demos/horizon-lab/race-runtime.js';
const HEADER='// SPDX-License-Identifier: Apache-2.0\n// Generated by scripts/horizon-race-runtime.mjs --write; checked against source.\nexport const raceRuntime = ';
const digest=bytes=>createHash('sha256').update(bytes).digest('hex');
const allowed=path=>/^(?:api|modules|demos\/horizon-lab)\/[a-zA-Z0-9_./-]+\.js$/.test(path)&&!path.split('/').some(p=>['.','..',''].includes(p));
async function local(root,path){
  let part=root,info;
  for(const name of path.split('/')){part=join(part,name);info=await lstat(part);if(info.isSymbolicLink())throw Error('Symlink in portable runtime: '+path);}
  if(!info.isFile())throw Error('Portable runtime must be a regular file: '+path);
  if(info.size>512*1024)throw Error('Portable source file exceeds 512 KiB');
  const bytes=await readFile(part);
  if(bytes.length>512*1024)throw Error('Portable source file exceeds 512 KiB');
  return bytes;
}
async function collectModules(root,entry,portable){
  const files=new Map(),pending=[entry];let size=0;
  while(pending.length){
    const path=pending.pop();if(files.has(path))continue;
    if(!allowed(path)||(portable&&(path===RUNTIME_ARCHIVE||path==='demos/horizon-lab/race-export.js')))throw Error('Unsupported portable dependency: '+path);
    const bytes=await local(root,path),source=new TextDecoder('utf-8',{fatal:true}).decode(bytes),links=[],deps=jsDependencies(source,(spec,start,end)=>links.push([start,end,resolveLocal(path,spec)]));
    if(deps.issues.length)throw Error('Unresolved portable dependency '+path+': '+deps.issues.join(', '));
    files.set(path,{text:source,links});size+=bytes.length;
    if(files.size>96||size>768*1024)throw Error('Portable runtime exceeds closure budget');
    for(const spec of deps.imports)pending.push(resolveLocal(path,spec));
  }
  return files;
}
const fileEntry='demos/horizon-lab/race-start.js';
const fileArchive='demos/horizon-lab/race-file.js';
async function authorFileSource(root){
  const modules=await collectModules(root,fileEntry,false);
  return fileModuleArchive(fileEntry,Object.fromEntries([...modules].map(([path,row])=>[path,fileModuleSource(row.text,row.links)])));
}
export async function runtimeArchive(root=ROOT){
  const files=await collectModules(root,'demos/horizon-lab/race-player.js',true);
  let size=[...files.values()].reduce((sum,row)=>sum+Buffer.byteLength(row.text),0);
  for(const path of ['demos/horizon-lab/race-launch.js','demos/horizon-lab/race-portable-shell.txt','demos/horizon-lab/race.css','LICENSE','NOTICE','offline/register.js']){
    const bytes=await local(root,path);size+=bytes.length;files.set(path,{text:new TextDecoder('utf-8',{fatal:true}).decode(bytes)});
  }
  const html=assetDependencies('index.html',files.get('demos/horizon-lab/race-portable-shell.txt').text);
  const expected=['./demos/horizon-lab/race-launch.js','./demos/horizon-lab/race.css','./game-start.js','./offline/register.js'].sort();
  if(html.issues.length||JSON.stringify(html.imports.sort())!==JSON.stringify(expected))throw Error('Portable shell must use only its declared stylesheet and declared local startup scripts');
  const css=assetDependencies('race.css',files.get('demos/horizon-lab/race.css').text);
  if(css.issues.length||css.imports.length)throw Error('Portable stylesheet must be self-contained');
  if(size>1024*1024)throw Error('Portable archive exceeds 1 MiB');
  const rows=[...files].sort(([a],[b])=>a.localeCompare(b)).map(([path,{text,links}])=>({path,text,sha256:digest(Buffer.from(text)),...(links?.length?{links}:{})}));
  return {format:'qsol.vanillajs.horizon-race-runtime.v1',files:rows,workerTemplate:new TextDecoder('utf-8',{fatal:true}).decode(await local(root,'scripts/service-worker.template.js'))};
}
export async function runtimeArchiveSource(root=ROOT){return HEADER+JSON.stringify(await runtimeArchive(root))+';\n';}
export async function verifyHorizonRaceRuntime(root=ROOT){
  if(await readFile(join(root,fileArchive),'utf8')!==await authorFileSource(root))throw Error('Stale HORIZON local-file archive; regenerate with --write');
  if(await readFile(join(root,RUNTIME_ARCHIVE),'utf8')!==await runtimeArchiveSource(root))throw Error('Stale HORIZON race portable runtime; run node scripts/horizon-race-runtime.mjs --write and review the generated diff');
}
if(process.argv[1]&&import.meta.url===pathToFileURL(resolve(process.argv[1])).href){
  const args=process.argv.slice(2);
  if(args.length===1&&args[0]==='--write'){await writeFile(join(ROOT,RUNTIME_ARCHIVE),await runtimeArchiveSource());await writeFile(join(ROOT,fileArchive),await authorFileSource(ROOT));console.log('Generated source-bound HORIZON race portable runtime.');}
  else if(args.length===0){await verifyHorizonRaceRuntime();console.log('Verified HORIZON race portable runtime against exact source bytes.');}
  else throw Error('Usage: node scripts/horizon-race-runtime.mjs [--write]');
}
