import {readFile,writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {hash,jsDependencies,resolveLocal} from './browser-dependencies.mjs';
const root=resolve(import.meta.dirname,'..'),identity='demos/block-arena-lab/identity.js';
export async function verifyFPSSource({write=false}={}){
  const pending=['demos/block-arena-lab/replay.js'],files=new Map();
  while(pending.length){const path=pending.pop();if(path===identity||files.has(path))continue;
    const source=await readFile(resolve(root,path),'utf8'),deps=jsDependencies(source);if(deps.issues.length)throw Error('FPS source dependency unresolved');
    files.set(path,hash(source));for(const spec of deps.imports)pending.push(resolveLocal(path,spec));
  }
  const source=hash(JSON.stringify([...files].sort(([a],[b])=>a<b?-1:1))),text=`// SPDX-License-Identifier: Apache-2.0\n// Generated by scripts/fps-source-identity.mjs --write; checked before packaging.\nexport const FPS_SOURCE='${source}';\n`;
  if(write)await writeFile(resolve(root,identity),text);else if(await readFile(resolve(root,identity),'utf8')!==text)throw Error('FPS source identity is stale: run node scripts/fps-source-identity.mjs --write');
  return {source,files:Object.fromEntries(files)};
}
if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url))console.log(JSON.stringify(await verifyFPSSource({write:process.argv.includes('--write')})));
