// A source-bound text archive, never imported project code. The browser can
// export a complete native-module game without network requests or a bundler.
import {readFile,writeFile,lstat} from 'node:fs/promises';
import {resolve,join} from 'node:path';
import {pathToFileURL} from 'node:url';
import {createHash} from 'node:crypto';
import {jsDependencies,assetDependencies,resolveLocal} from './browser-dependencies.mjs';
const ROOT=resolve(import.meta.dirname,'..');
export const RUNTIME_ARCHIVE='demos/game-maker-lab/portable-runtime.js';
const HEADER='// SPDX-License-Identifier: Apache-2.0\n// Generated by scripts/game-maker-runtime.mjs --write; checked against source.\nexport const portableRuntime = ';
const digest=bytes=>createHash('sha256').update(bytes).digest('hex');
const allowed=path=>/^(?:api|modules|demos\/game-maker-lab)\/[a-zA-Z0-9_./-]+\.js$/.test(path)&&!path.split('/').some(p=>['.','..',''].includes(p));
async function local(root,path){
  let part=root;
  for(const name of path.split('/')){part=join(part,name);if((await lstat(part)).isSymbolicLink())throw Error('Symlink in portable runtime: '+path);}
  const bytes=await readFile(part);
  if(bytes.length>512*1024)throw Error('Portable source file exceeds 512 KiB');
  return bytes;
}
export async function runtimeArchive(root=ROOT){
  const files=new Map(),pending=['demos/game-maker-lab/portable.js'];let size=0;
  while(pending.length){
    const path=pending.pop();if(files.has(path))continue;
    if(!allowed(path)||path===RUNTIME_ARCHIVE||path==='demos/game-maker-lab/export.js')throw Error('Unsupported portable dependency: '+path);
    const bytes=await local(root,path),source=new TextDecoder('utf-8',{fatal:true}).decode(bytes),deps=jsDependencies(source);
    if(deps.issues.length)throw Error('Unresolved portable dependency '+path+': '+deps.issues.join(', '));
    files.set(path,source);size+=bytes.length;
    if(files.size>96||size>768*1024)throw Error('Portable runtime exceeds closure budget');
    for(const spec of deps.imports)pending.push(resolveLocal(path,spec));
  }
  for(const path of ['demos/game-maker-lab/portable-shell.txt','demos/game-maker-lab/style.css','LICENSE','NOTICE','offline/register.js']){
    const bytes=await local(root,path);size+=bytes.length;files.set(path,new TextDecoder('utf-8',{fatal:true}).decode(bytes));
  }
  const html=assetDependencies('index.html',files.get('demos/game-maker-lab/portable-shell.txt'));
  const expected=['./demos/game-maker-lab/style.css','./game-start.js','./offline/register.js'].sort();
  if(html.issues.length||JSON.stringify(html.imports.sort())!==JSON.stringify(expected))throw Error('Portable shell must use only its declared stylesheet and two local module entries');
  const css=assetDependencies('style.css',files.get('demos/game-maker-lab/style.css'));
  if(css.issues.length||css.imports.length)throw Error('Portable stylesheet must be self-contained');
  if(size>1024*1024)throw Error('Portable archive exceeds 1 MiB');
  const rows=[...files].sort(([a],[b])=>a.localeCompare(b)).map(([path,text])=>({path,text,sha256:digest(Buffer.from(text))}));
  return {format:'qsol.vanillajs.game-maker-runtime.v1',files:rows,workerTemplate:new TextDecoder('utf-8',{fatal:true}).decode(await local(root,'scripts/service-worker.template.js'))};
}
export async function runtimeArchiveSource(root=ROOT){return HEADER+JSON.stringify(await runtimeArchive(root))+';\n';}
export async function verifyGameMakerRuntime(root=ROOT){
  if(await readFile(join(root,RUNTIME_ARCHIVE),'utf8')!==await runtimeArchiveSource(root))throw Error('Stale Game Maker portable runtime; run node scripts/game-maker-runtime.mjs --write and review the generated diff');
}
if(process.argv[1]&&import.meta.url===pathToFileURL(resolve(process.argv[1])).href){
  const args=process.argv.slice(2);
  if(args.length===1&&args[0]==='--write'){await writeFile(join(ROOT,RUNTIME_ARCHIVE),await runtimeArchiveSource());console.log('Generated source-bound Game Maker portable runtime.');}
  else if(args.length===0){await verifyGameMakerRuntime();console.log('Verified Game Maker portable runtime against exact source bytes.');}
  else throw Error('Usage: node scripts/game-maker-runtime.mjs [--write]');
}
